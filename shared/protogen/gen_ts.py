#!/usr/bin/env python3
"""Generate the TypeScript protocol tables and message types from the server's protocols.json (the single source of truth).

  python3 shared/protogen/gen_ts.py <protocols.json> <out-dir>

Writes <out-dir>/schema.ts (compact field tables, one per command and direction) and <out-dir>/messages.ts (typed interfaces).
Field table entry: [name, type] or [name, "array", [children...]]. Direction names are the client's view, like the server's:
send = client -> server, recv = server -> client.
"""
import json
import re
import sys

sys.dont_write_bytecode = True
TS_TYPE = {"uint8": "number", "uint16": "number", "uint32": "number", "int8": "number", "int16": "number", "int32": "number",
           "byte": "number", "uint64": "bigint", "string": "string"}
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def norm(fields):
    """The exporter writes an empty Lua table as {} instead of []."""
    return fields if isinstance(fields, list) else []


def compact(fields):
    out = []
    for f in norm(fields):
        if f["type"] == "array":
            out.append([f["name"], "array", compact(f.get("fields"))])
        else:
            out.append([f["name"], f["type"]])
    return out


def ts_type(fields, ind=1):
    pad = "  " * ind
    lines = []
    for f in norm(fields):
        key = f["name"] if IDENT.match(f["name"]) else json.dumps(f["name"])
        if f["type"] == "array":
            inner = ts_type(f.get("fields"), ind + 1)
            lines.append(f"{pad}{key}: Array<{{\n{inner}\n{pad}}}>;" if inner else f"{pad}{key}: Array<Record<string, never>>;")
        else:
            lines.append(f"{pad}{key}: {TS_TYPE[f['type']]};")
    return "\n".join(lines)


def main(src, out):
    d = json.load(open(src))
    schema = ["// Generated by shared/protogen/gen_ts.py from protocols.json. Do not edit.",
              "export type Field = readonly [name: string, type: string, children?: readonly Field[]];"]
    msgs = ["// Generated by shared/protogen/gen_ts.py from protocols.json. Do not edit.",
            "// C<cmd>: client -> server, S<cmd>: server -> client. uint64 fields are bigint, every other integer is number."]
    for direction, const, prefix in (("send", "send", "C"), ("recv", "recv", "S")):
        entries = []
        for cmd in sorted(d[direction], key=int):
            entries.append(f'{cmd}:{json.dumps(compact(d[direction][cmd]), ensure_ascii=False, separators=(",", ":"))}')
            body = ts_type(d[direction][cmd])
            msgs.append(f"export interface {prefix}{cmd} {{\n{body}\n}}" if body else f"export type {prefix}{cmd} = Record<string, never>;")
        schema.append(f"export const {const}: Readonly<Record<number, readonly Field[]>> = {{{','.join(entries)}}};")
    open(f"{out}/schema.ts", "w").write("\n".join(schema) + "\n")
    open(f"{out}/messages.ts", "w").write("\n".join(msgs) + "\n")
    print(f"{len(d['send'])} send and {len(d['recv'])} recv messages")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
